#! /usr/bin/perl

my $FILE = shift ;
die "Usage: $0 <filename>" unless $FILE ;

our $usingSubversion = '#define FROM_SUBVERSION 1' ;
our $usingMercurial  = '#undef  FROM_MERCURIAL' ;

our $revision = `svnversion` ;
our $url = 'repository' ;
our $hgBranch = 'n/a', $hgRevision = 'n/a' ;
$revision =~ s/[\r\n]+//g ;
if ( $revision eq 'exported' )
{
 $usingSubversion = '#undef  FROM_SUBVERION' ;
 $usingMercurial =  '#define FROM_MERCURIAL 1' ;
 my $hgInfo = `hg id -i -b` ;
 my ($hgRevision, $hgBranch) = split(' ', $hgInfo) ;
 $revision = "$hgBranch/$hgRevision"
 
}
else
{
 our $url = `svn info . | grep URL:` ;
 $url =~ s!^URL:\s+http://[^/]+/svn/[^/]+/(.*)/WW2/src/?[\r\n]+$!$1!s ;
}

open(OUT, ">$FILE.new") ;
print OUT <<END;
#pragma once
// ---------- AUTOMATICALLY GENERATED BY $0 $FILE ----------
$usingSubversion
$usingMercurial

// String description of the build repository versions
#define REPOSITORY_INFO "${url} ${revision}"
END
close(OUT) ;

if ( ! -f $FILE ) {
 print("* Creating $FILE\n") ;
 rename("$FILE.new", "$FILE") ;
} elsif ( `diff --brief $FILE.new $FILE` ) {
 print("* Updating $FILE\n") ;
 unlink("$FILE") ;
 rename("$FILE.new", "$FILE") ;
} else {
 unlink("$FILE.new") ;
}

