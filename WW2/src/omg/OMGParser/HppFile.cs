using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace OMG
{
    /// <summary>
    /// Header file.
    /// </summary>
    public class HppFile : OMG.File
    {
        public HppFile(string srcFile, Element parent)
            : base(srcFile, ".hpp", parent)
        {
            GuardString = "OMG." + Name;
            GuardString = GuardString.Replace(".", "_");
            GuardString = GuardString.ToUpper();
        }

        public string GuardString { get; private set; }

        protected override void Preamble()
        {
            lines.Add("#ifndef " + GuardString);
            lines.Add("#define " + GuardString + " 1");
            lines.Add("// This file was automatically generated by OMG from " + SrcFilename);
            lines.Add("// DO NOT EDIT BY HAND.");
            lines.Add("");

            IncludeFiles();
        }

        protected override void Prolog()
        {
            lines.Add("namespace OMG");
            lines.Add("{");
            lines.Add("");

            BriefDoc();
            DetailDoc();
        }

        protected override void Epilog()
        {
            lines.Add("");
            lines.Add("} // namespace OMG");
            lines.Add("");
            lines.Add("#endif // " + GuardString);
        }
    }

}
