using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace OMG
{
    public class CppFile : OMG.File
    {
        public CppFile(string srcFile, Element parent)
            : base(srcFile, ".cc", parent)
        {
            string headerFile = srcFile.Replace(".xml", ".hpp");
            AddInclude(headerFile, "Class header file.");
        }

        protected override void Preamble()
        {
            lines.Add("// This file was automatically generated by OMG from " + SrcFilename);
            lines.Add("// DO NOT EDIT BY HAND.");
            lines.Add("");
        }

        protected override void Prolog()
        {
            BriefDoc();
            IncludeFiles();
            DetailDoc();
        }

        protected override void Content(string indent)
        {
            lines.Add("// Content");
        }

        protected override void Epilog()
        {
            lines.Add("// Epilog");
        }
    }
}
