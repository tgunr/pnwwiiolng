					//locale = setlocale(LC_ALL, "english");

					candidates.style		= list->dwStyle;
					candidates.count		= list->dwCount;
					candidates.selection = list->dwSelection;
					candidates.start		= list->dwPageStart;
					candidates.page		= list->dwPageSize;

