#include "chat/chatDefines.h"		// For MAX_CLIENT_CHANNELS

namespace Chat
{
	// Structure of messages sent from the host to the client
	// Used on both client/host, some fields on the host are
	// not transmitted to the client.
	struct HostMessage
	{
		bool	isDotMessage;		// True when generated by a .command
		UINT32	auxChanType;		// superceedes country
		UINT32	length;				// Size in bytes
		UINT32	id;					// IDs are assigned by the host to
									// prevent duplicates but not sent
									// to the client.
		UCHAR	radioType[MAX_CLIENT_CHANNELS];
									// Channel indices it was xmitted on
		UCHAR	icon;				// Icon of the message - which may
									// happen to be the country too.
		ChatHandle	handle;			// Packed handle of the sender
		const char* msg;			// Pointer to the message

		// Member functions
		SINT32 packer(LOGICAL MODE, ACTION_OBJECT* a);
	};
}

