{
	char			name[CONFIG_NAME_SIZE+1];
	void*			var;
	cfgPARAM_TYPES	type;
	unsigned int	dynamic; // does this var require a restart to take effect
	int				min; // min value; 0 for strings
	int				max; // max value; length for strings
	bool			active; // is this pref in use or not
};

