function unitSetFallback(unitName)
 local unit = getHcUnit(unitName)
 if unit == nil then return error("unknown unit: " ..unitName) end
 if unit:isBrigade() and unit:parent() ~= nil then
  setHcUnitFallbackDestination(unit, unit:parent():homeCP())
 end
end

