#! /bin/bash

 die () { echo ERROR: $*; exit 1 ; }


#################### Vagrant box setup.
#
# You'll need to have 'vagrant' installed
# This script installs the box image for you, registers it as 'trusty',
# and brings the machine up provisioned.
#
# You'll also need a provider: virtualbox or vmware. Default is virtualbox.

if [ -d ".vagrant" ]; then
  die "WARNING: .vagrant folder already exists. Use 'vagrant destroy' to remove it? Aborting. "
fi

#################### Configuration

# You can override these with, e.g. PROVIDER=vmware ./bootstrap.sh

# Which virtual machine provider to use.
PROVIDER=${PROVIDER:-virtualbox}

# Local name for the box.
BOXNAME=${BOXNAME:-trusty}

# Source of the box.
BOXURL=${BOXURL:-https://cloud-images.ubuntu.com/vagrant/trusty/current/trusty-server-cloudimg-amd64-vagrant-disk1.box}

# Virtual machine config
BOXCPUS=${BOXCPUS:-4}
BOXMEMMB=${BOXMEMMB:-800}
srcDir=$(cd $(dirname $0)/../.. ; pwd -P)

#################### Code

echo "INFO: Checking packages"
sudo aptitude update -y
sudo aptitude install -y vagrant virtualbox virtualbox-dkms || die "Unable to install packages"

# Generate the Vagrant file.

echo "INFO: Generating Vagrantfile"
echo >Vagrantfile "### AUTOMATICALLY GENERATED BY $0

# Vagrantfile API/syntax version. Don't touch unless you know what you're doing!
VAGRANTFILE_API_VERSION = '2'

Vagrant.configure(VAGRANTFILE_API_VERSION) do |config|

  # From ${BOXURL}
  config.vm.box = '${BOXNAME}'

  config.vm.provision :shell, path: 'vagrant_provision.sh'

  config.vm.synced_folder '${srcDir}', '/playnet/wwiiolng'

  config.ssh.forward_agent = true
  
  config.vm.provider 'virtualbox' do |vb|

  #  # Don't boot with headless mode
  #  vb.gui = true

    vb.customize [ 'modifyvm', :id, '--memory', '${BOXMEMMB}' ]

    vb.customize [ 'modifyvm', :id, '--ioapic', 'on' ]
    vb.customize [ 'modifyvm', :id, '--cpus', ${BOXCPUS} ]

  end

end
"

# Add the box to the local system
echo "INFO: Downloading/registering ${BOXNAME} ${PROVIDER} box from ${BOXURL}"
echo "INFO: If this has already been registered, you can ignore the error from vagrant"
vagrant box add -c --provider "${PROVIDER}" "${BOXNAME}" "${BOXURL}"

# Fire up the virtual machine and provision it.
echo "INFO: Starting the virtual machine and provisioning script"
vagrant up --provision --provider virtualbox --parallel


echo "INFO: Ready to go, from $(pwd) type 'vagrant ssh' to log in to the machine."
echo "INFO: The '${srcDir}' directory will be shared with the virtual machine as /playnet/wwiiolng"
echo

